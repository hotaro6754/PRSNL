async def metrics_snapshot_task():
    global last_flows_processed
    while True:
        try:
            current_flows = FLOWS_PROCESSED._value.get()
            flows_sec = (current_flows - last_flows_processed) / 5.0
            last_flows_processed = current_flows
            
            metrics_history.append({
                "timestamp": datetime.now(timezone.utc).isoformat(),
                "flows_per_sec": flows_sec,
                "total_active_cases": len([c for c in correlation_engine.get_all_cases() if c.status == "OPEN"]),
                "alerts_per_min": round(ALERTS_GENERATED._value.get() / max(1, (time.time() - telemetry["start_time"]) / 60), 2)
            })
        except Exception as e:
            logger.error("Error in metrics snapshot: %s", e)
        await asyncio.sleep(5)


# ── Alert Broadcasting ─────────────────────────────────────────────────
async def broadcast_alerts():
    """Reads alerts from the queue, correlates, persists, and broadcasts."""
    while True:
        alert: Alert = await alert_queue.get()
        telemetry["total_alerts"] += 1
        ALERTS_GENERATED.inc()

        # Correlate
        updated_case = correlation_engine.ingest_alert(alert)
        ACTIVE_CASES.set(len([c for c in correlation_engine.get_all_cases() if c.status == "OPEN"]))

        # Persist asynchronously (never blocks detection)
        try:
            await mongo.save_alert(alert.model_dump(mode="json"))
            if updated_case:
                await mongo.upsert_case(updated_case.model_dump(mode="json"))
        except Exception as e:
            logger.error("Persistence error (detection continues): %s", e)

        # Instead of broadcasting instantly, push to a batch queue to prevent WS explosion
        ws_message_queue.append({
            "type": "NEW_ALERT",
            "alert": alert.model_dump(mode="json"),
            "case": updated_case.model_dump(mode="json") if updated_case else None,
        })

# ── Kafka Consumer ─────────────────────────────────────────────────────
async def kafka_consumer_task():
    """Consumes live traffic from Kafka/Redpanda."""
    try:
        from backend.streaming.kafka_adapter import KafkaObservationConsumer
        consumer = KafkaObservationConsumer()
        if not consumer.enabled:
            logger.info("Kafka not available — live streaming disabled (PCAP replay still works)")
            return

        logger.info("Starting Kafka consumer...")
        loop = asyncio.get_running_loop()

        def _consume():
            for flow in consumer.consume():
                asyncio.run_coroutine_threadsafe(_process_flow(flow), loop)

        await loop.run_in_executor(None, _consume)
    except Exception as e:
        logger.warning("Kafka consumer failed: %s — detection continues via PCAP replay", e)


async def process_window(wid: int, src_ip: str, window_flows: List[NetworkObservation]):
    telemetry["total_feature_windows"] += 1
    
    # 1. Deterministic detection
    det_alerts = []
    for detector in detectors:
        det_alerts.extend(detector.evaluate_window(window_flows, wid))
        
    # 2. Feature extraction
    fv = feature_engine.extract_features(window_flows)
    
    # 3. ML inference
    ml_pred = None
    if fv is not None:
        flow = window_flows[0]
        ml_pred = model_router.evaluate(fv, flow)
        if ml_pred is not None:
            telemetry["total_ml_inferences"] += 1
            ML_INFERENCES.inc()
            try:
                await mongo.save_prediction(ml_pred.model_dump(mode="json"))
            except Exception:
                pass

    # 4. Evidence fusion
    if len(window_flows) > 0:
        final_alerts = fusion_engine.fuse(det_alerts, ml_pred, window_flows[0])
        for alert in final_alerts:
            await alert_queue.put(alert)


async def _process_flow(flow):
    """Process a single NetworkObservation through the full pipeline."""
    telemetry["total_flows"] += 1
    FLOWS_PROCESSED.inc()
    window_manager.add_observation(flow)
    redis_host_manager.add_flow(flow)


# ── PCAP Replay ────────────────────────────────────────────────────────
class ReplayRequest(BaseModel):
    filename: str


def process_pcap_background(filename: str, loop: asyncio.AbstractEventLoop):
    """Background thread: replay PCAP through the full pipeline."""
    logger.info("Starting PCAP replay: %s", filename)
    try:
        adapter = ScapyAdapter()
        for flow in adapter.consume(filename):
            telemetry["total_flows"] += 1
            FLOWS_PROCESSED.inc()
            window_manager.add_observation(flow)
            redis_host_manager.add_flow(flow)
            
            ready_windows = window_manager.flush_ready_windows(0, is_live=False)
            for wid, src_ip, window_flows in ready_windows:
                asyncio.run_coroutine_threadsafe(process_window(wid, src_ip, window_flows), loop)

        # Final flush
        final_windows = window_manager.flush_all()
        for wid, src_ip, window_flows in final_windows:
            asyncio.run_coroutine_threadsafe(process_window(wid, src_ip, window_flows), loop)

    except Exception as e:
        logger.error("PCAP replay error: %s", e, exc_info=True)
    finally:
        logger.info("PCAP replay finished: %s", filename)


async def window_tick_task():
    logger.info("Starting WindowManager live tick task...")
    while True:
        try:
            now_ms = int(time.time() * 1000)
            ready_windows = window_manager.flush_ready_windows(now_ms, is_live=True)
            for wid, src_ip, window_flows in ready_windows:
                await process_window(wid, src_ip, window_flows)
        except Exception as e:
            logger.error("Error in window tick: %s", e)
        await asyncio.sleep(0.5)

