@app.get("/api/ml/metrics")
async def get_ml_metrics():
    import json
    import os

    metadata_path = os.path.join(os.path.dirname(__file__), '../models/url_xgb_v1_metadata.json')
    try:
        with open(metadata_path, 'r') as f:
            meta = json.load(f)
        return meta
    except Exception as e:
        return {"error": str(e)}

