@app.get("/api/cases/{case_id}")
async def get_case_by_id(case_id: str, tenant_id: str = Depends(get_current_tenant)):
    case = None
    cases = correlation_engine.get_all_cases()
    for c in cases:
        if str(c.case_id) == case_id and getattr(c, 'organization_id', 'default_org') == tenant_id:
            case = c.model_dump() if hasattr(c, 'model_dump') else c
            break
            
    if not case:
        try:
            from bson import ObjectId
            db_case = await mongo.cases.find_one({"case_id": case_id, "organization_id": tenant_id})
            if db_case:
                if "_id" in db_case:
                    del db_case["_id"]
                case = db_case
        except Exception:
            pass

    if not case:
        raise HTTPException(status_code=404, detail="Case not found")

    # Ensure 5-layer explanation is attached to the case object for the frontend
    if "explanation" not in case or not case["explanation"]:
        severity = case.get("severity", "UNKNOWN")
        threat_type = case.get("threat_summary", "Anomaly")
        entity_type = (case.get("primary_entity_type") or "network/host").upper()
        entity = case.get("primary_entity") or case.get("source_ip") or "Unknown Entity"
        
        alerts = case.get("alerts", [])
        evidence_list = []
        for a in alerts:
            if "evidence" in a and isinstance(a["evidence"], list):
                for ev in a["evidence"]:
                    evidence_list.append(f"{ev.get('feature', 'indicator')}: {ev.get('value', 'unknown')} (Contribution: {ev.get('contribution', 0)})")
            else:
                evidence_list.append(f"Detected {a.get('threat_class', 'suspicious behavior')} from {a.get('source_ip', 'unknown')}")
        
        if not evidence_list:
            evidence_list = [f"Raw indicator: {threat_type} flagged by Risk Engine."]

        action = "Immediate remediation required. Isolate host and rotate credentials." if severity in ["CRITICAL", "HIGH"] else "Monitor for further anomalous activity."
        if entity_type in ["URL", "EMAIL", "SMS", "QR"]:
            action = f"Block interaction with this {entity_type} payload and alert the targeted user." if severity in ["CRITICAL", "HIGH"] else f"No immediate action required. This {entity_type} appears benign."

        case["explanation"] = {
            "what": f"CyberOS detected a {severity} risk event involving {entity_type}: {entity[:50]}.",
            "why": f"The Risk Engine classified this as '{threat_type}' due to correlated signals surpassing the acceptable anomaly threshold.",
            "evidence_summary": evidence_list[:6],
            "confidence": "System confidence is HIGH based on direct ML inference and deterministic rules." if severity in ["CRITICAL", "HIGH"] else "System confidence is MEDIUM due to isolated/weak signals.",
            "action": action,
            "uncertainty": "Telemetry may be incomplete if the payload was encrypted or if the host is outside the managed boundary."
        }
        
    return case

@app.get("/api/cases/{case_id}/graph")
async def get_case_graph(case_id: str, tenant_id: str = Depends(get_current_tenant)):
    case = await get_case_by_id(case_id, tenant_id)
    if not case:
        raise HTTPException(status_code=404, detail="Case not found")
        
    case_dict = case.model_dump() if hasattr(case, "model_dump") else case
    
    nodes = {}
    edges = set()
    
    def add_node(n_id, n_type):
        if not n_id or not isinstance(n_id, str): return
        n_type = n_type.upper()
        if n_id not in nodes:
            nodes[n_id] = {"id": n_id, "type": n_type, "label": n_id}
            
    def add_edge(src, tgt, rel):
        if not src or not tgt or not isinstance(src, str) or not isinstance(tgt, str): return
        edges.add((src, tgt, rel))
        
    p_id = case_dict.get("primary_entity")
    p_type = case_dict.get("primary_entity_type")
    if p_id and p_type:
        add_node(p_id, p_type)
        
    src_ip = case_dict.get("source_ip")
    if src_ip:
        add_node(src_ip, "IP")
        if p_id:
            add_edge(src_ip, p_id, "observed_by")
            
    for alert in case_dict.get("alerts", []):
        alert_src = alert.get("source_ip")
        alert_dst = alert.get("dest_ip")
        if alert_src: add_node(alert_src, "IP")
        if alert_dst: add_node(alert_dst, "IP")
        if alert_src and alert_dst:
            add_edge(alert_src, alert_dst, "communicates_with")
            
        domain = alert.get("domain")
        if domain:
            add_node(domain, "DOMAIN")
            if alert_src: add_edge(alert_src, domain, "communicates_with")
            if alert_dst: add_edge(domain, alert_dst, "resolves_to")
            
    for ev in case_dict.get("evidence", []):
        if not isinstance(ev, dict):
            continue
            
        url = ev.get("url")
        ev_type = ev.get("evidence_type", "").upper()
        cat = ev.get("category", "").upper()
        val = ev.get("value")
        
        if url:
            add_node(url, "URL")
            if ev_type == "QR":
                qr_node = f"QR_{url[-10:]}"
                add_node(qr_node, "QR")
                add_edge(qr_node, url, "contains")
                
        if val and isinstance(val, str) and cat in ["URL", "DOMAIN", "IP", "EMAIL", "PHONE", "HASH", "USER", "HOST", "MESSAGE", "QR"]:
            add_node(val, cat)
            if p_id:
                add_edge(p_id, val, "contains")
                
        details = ev.get("details", {})
        if isinstance(details, dict):
            for k, v in details.items():
                if k in ["resolves_to", "redirects_to", "downloads", "hosts", "extracts", "contains", "sent_by", "sent_to", "communicates_with", "related_to", "observed_by"]:
                    src = url or p_id
                    if isinstance(v, str) and src:
                        add_node(v, "UNKNOWN")
                        add_edge(src, v, k)
                    elif isinstance(v, list) and src:
                        for item in v:
                            if isinstance(item, str):
                                add_node(item, "UNKNOWN")
                                add_edge(src, item, k)
                                
    return {
        "nodes": list(nodes.values()),
        "edges": [{"source": s, "target": t, "type": r} for s, t, r in edges]
    }

